make_run <- function(name) {
  run <- file.path(trio, name)
  dir.create(file.path(run, "metadata"), recursive = TRUE)
  dir.create(file.path(run, "statistics", "singlenuc"), recursive = TRUE)
  entries <- lapply(2:3, function(i) list(slot = paste0("org", i), role = "ingroup", accession = paste0("ACC", i), short_name = paste0("S", i), raw_organism_name = "Species name", metadata_json = "/stale/path"))
  jsonlite::write_json(list(organisms = entries), file.path(run, "metadata", "metadata_manifest.json"), auto_unbox = TRUE)
  df <- data.frame(mutType = shape_channels(), mutNum = 1:96, totalRootNum = 1000)
  write.table(df, file.path(run, "statistics", "singlenuc", "ACC2_S2_test_maflinked.tsv"), sep = "\t", row.names = FALSE, quote = FALSE)
  write.table(df, file.path(run, "statistics", "singlenuc", "cds_from_S3_test.tsv"), sep = "\t", row.names = FALSE, quote = FALSE)
  write.table(df, file.path(run, "statistics", "singlenuc", "ACC2_S2_test_ncds.tsv"), sep = "\t", row.names = FALSE, quote = FALSE)
  dir.create(file.path(run, "statistics", "singlenuc", "without_maflinked"))
  file.copy(file.path(run, "statistics", "singlenuc", "ACC2_S2_test_maflinked.tsv"), file.path(run, "statistics", "singlenuc", "without_maflinked", "ACC2_S2_backup.tsv"))
  run
}
